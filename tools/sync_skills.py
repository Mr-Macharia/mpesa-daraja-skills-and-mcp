#!/usr/bin/env python3
"""Make every skill self-contained from one set of sources.

Sources of truth:
  mcp-server/src/mpesa_mcp/helpers.py     -> <skill>/scripts/daraja_helpers.py
  mcp-server/src/mpesa_mcp/validation.py  -> <skill>/scripts/daraja_validation.py
  shared/scripts/*.py                     -> <skill>/scripts/<name>.py
  helpers.RESULT_CODES                    -> daraja-troubleshooting/reference.md

Usage:
  python tools/sync_skills.py          # write the copies
  python tools/sync_skills.py --check  # exit 1 if any copy is missing or stale (CI)
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "mcp-server" / "src" / "mpesa_mcp"
SHARED = ROOT / "shared" / "scripts"
SKILLS = ROOT / "skills"

LIBRARIES = {
    "daraja_helpers.py": PKG / "helpers.py",
    "daraja_validation.py": PKG / "validation.py",
}
# Which library each shared script imports.
NEEDS = {
    "validate_request.py": ["daraja_validation.py"],
    "parse_callback.py": ["daraja_helpers.py"],
    "explain_code.py": ["daraja_helpers.py"],
    "stk_password.py": ["daraja_helpers.py"],
    "check_token.py": [],
    "security_credential.py": [],
    "check_integration.py": [],
    "sales_log.py": [],
}
# Scripts each skill's SKILL.md runs.
MANIFEST = {
    "mpesa-daraja": ["validate_request.py"],
    "daraja-auth": ["check_token.py"],
    "daraja-stk-push": ["stk_password.py", "validate_request.py"],
    "daraja-c2b": ["validate_request.py"],
    "daraja-b2c": ["validate_request.py", "parse_callback.py"],
    "daraja-b2b": ["validate_request.py"],
    "daraja-tax-remittance": ["validate_request.py"],
    "daraja-ratiba": ["validate_request.py"],
    "daraja-dynamic-qr": ["validate_request.py"],
    "daraja-account-ops": ["parse_callback.py"],
    "daraja-callbacks": ["parse_callback.py"],
    "daraja-credentials-security": ["security_credential.py"],
    "daraja-sandbox-setup": ["check_token.py", "security_credential.py"],
    "daraja-troubleshooting": ["explain_code.py", "validate_request.py", "check_token.py"],
    "daraja-bill-manager": [],
    "daraja-payment-design": ["check_integration.py"],
    "daraja-checkout": ["check_integration.py"],
    "daraja-payouts": [],
    "daraja-paybill-collections": [],
    "daraja-recurring-billing": [],
    "daraja-agent-storefront": ["sales_log.py"],
}

HEADER = "# GENERATED by tools/sync_skills.py from {src} - edit the source, not this copy.\n"


def _load_helpers():
    spec = importlib.util.spec_from_file_location("daraja_helpers", PKG / "helpers.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _with_header(text: str, src: Path) -> str:
    header = HEADER.format(src=src.relative_to(ROOT).as_posix())
    if text.startswith("#!"):
        shebang, _, rest = text.partition("\n")
        return f"{shebang}\n{header}{rest}"
    return header + text


def expected_files() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for skill, scripts in MANIFEST.items():
        out = SKILLS / skill / "scripts"
        libs = {lib for s in scripts for lib in NEEDS[s]}
        for name in scripts:
            files[out / name] = _with_header((SHARED / name).read_text(encoding="utf-8"), SHARED / name)
        for lib in libs:
            files[out / lib] = _with_header(LIBRARIES[lib].read_text(encoding="utf-8"), LIBRARIES[lib])
    files[SKILLS / "daraja-troubleshooting" / "reference.md"] = code_reference(_load_helpers().RESULT_CODES)
    return files


def code_reference(codes: dict[str, str]) -> str:
    groups = {
        "Gateway / synchronous errorCodes": lambda c: "." in c,
        "C2B validation reject codes": lambda c: c.startswith("C2B"),
        "Reversal codes": lambda c: c.startswith("R0"),
        "Async ResultCodes (callbacks, queries)": lambda c: c.isdigit(),
    }
    out = ["# Daraja code reference", "",
           "<!-- GENERATED by tools/sync_skills.py from helpers.RESULT_CODES - do not edit by hand. -->", "",
           "Source: the Daraja 3.0 portal error tables for each API. `scripts/explain_code.py` searches the same data.",
           "", "## Contents"] + [f"- {g}" for g in groups] + [""]
    for title, pred in groups.items():
        out += [f"## {title}", "", "| Code | Meaning / fix |", "|---|---|"]
        out += [f"| `{c}` | {m} |" for c, m in codes.items() if pred(c)]
        out.append("")
    out += ["## HTTP status quick map", "", "| HTTP | Typical cause |", "|---|---|",
            "| 400 | Malformed or invalid field: read errorMessage |",
            "| 401 / 404.001.03 | Token expired or from the other environment |",
            "| 404 | Wrong URL/version |", "| 405 | Wrong method (product APIs are POST) |",
            "| 429 / 500.003.02 | Rate limit / spike arrest |",
            "| 500 | M-Pesa business error (500.001.1001) or internal |",
            "| 503 | Maintenance: retry with backoff |", ""]
    return "\n".join(out)


def stale_scripts(expected: dict[Path, str]) -> list[Path]:
    """Script files in skills that the manifest no longer produces."""
    present = {p for p in SKILLS.glob("*/scripts/*") if p.is_file() and p.name != "__pycache__"}
    return sorted(present - set(expected))


def main() -> int:
    check = "--check" in sys.argv
    expected = expected_files()
    problems = [p for p, text in expected.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    extra = stale_scripts(expected)
    if check:
        for p in problems:
            print(f"out of date: {p.relative_to(ROOT)}")
        for p in extra:
            print(f"not in manifest: {p.relative_to(ROOT)}")
        if problems or extra:
            print("Run: python tools/sync_skills.py")
            return 1
        print("skills in sync")
        return 0
    for p in problems:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(expected[p], encoding="utf-8")
        p.chmod(0o755 if p.suffix == ".py" and expected[p].startswith("#!") else 0o644)
    for p in extra:
        p.unlink()
    print(f"wrote {len(problems)} file(s), removed {len(extra)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
